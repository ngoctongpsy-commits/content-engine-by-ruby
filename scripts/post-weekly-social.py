"""
post-weekly-social.py — config-driven social post fire (generic, brand-agnostic)

Reads:
  - config/brand.json — forbidden phrases, validated stats, palette
  - config/channels.json — CMS, Make.com webhook + API, schedule, notifications
  - outputs/social/pending/weekly-*.json — packet generated by weekly-social-packet skill

Output:
  - PNG render of clickbait_svg
  - Upload to CMS /files endpoint
  - Fire 2+ webhooks to Make.com (one per enabled channel)
  - Verify Make.com execution status (Fix 1)
  - Telegram alert success or failure

Generic — no hardcoded brand. Forks for other brands just edit config/.
Built by Ruby for the Content Engine plugin.
"""
