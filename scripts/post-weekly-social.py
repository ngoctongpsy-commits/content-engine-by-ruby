def extract_stat_claims_from_svg(svg: str) -> list:
    import re
    text_blocks = re.findall(r"<text[^>]*>(.*?)</text>", svg, flags=re.DOTALL | re.IGNORECASE)
    blob = re.sub(r"<[^>]+>", " ", "\n".join(text_blocks))
    claims = set()
    for m in re.findall(r"\b\d+(?:\.\d+)?%", blob):
        claims.add(m)
    for m in re.findall(r"\b\d+(?:\.\d+)?x\b", blob):
        claims.add(m)
    for m in re.findall(r"\$\d+(?:\.\d+)?[KMB]?\b", blob):
        claims.add(m)
    return sorted(claims)


def validate_post_text(text: str, brand: dict, label: str = "post") -> tuple:
    """Validate post body against brand voice rules from config."""
    errors = []
    if not text:
        return False, [f"{label}: empty text"]
    tl = text.lower()

    voice = brand.get("voice", {})
    forbidden = voice.get("forbidden_phrases", {})
    chars = voice.get("forbidden_chars", {})

    if chars.get("em_dash") and "—" in text:
        errors.append(f"{label}: contains em dash (—)")
    if chars.get("en_dash") and "–" in text:
        errors.append(f"{label}: contains en dash (–)")
    if chars.get("emoji"):
        for ch in text:
            cp = ord(ch)
            if (0x1F300 <= cp <= 0x1FAFF) or (0x2600 <= cp <= 0x27BF):
                errors.append(f"{label}: contains emoji U+{cp:04X}")
                break

    for tell in forbidden.get("ai_tells", []):
        if tell.lower() in tl:
            errors.append(f"{label}: contains AI tell '{tell}'")

    approved_only = set(p.lower() for p in voice.get("required_phrasings", {}).get("approved_only_phrasings", []))
    for claim in forbidden.get("overclaims", []):
        if claim.lower() in tl and not any(a in tl for a in approved_only):
            errors.append(f"{label}: contains overclaim '{claim}'")

    return len(errors) == 0, errors


def validate_clickbait_svg(svg: str, brand: dict) -> tuple:
    """Validate SVG against brand palette + forbidden colors + required wordmark."""
    errors = []
    if not svg or not isinstance(svg, str):
        return False, ["SVG empty"]
    s = svg.strip()
    if not s.startswith("<svg") or not s.rstrip().endswith("</svg>"):
        errors.append("SVG must start with <svg and end with </svg>")
    sl = s.lower()

    palette = brand.get("palette", {})
    forbidden_colors = palette.get("_forbidden_colors", {})
    company = brand.get("company", {})

    # Brand wordmark required
    domain = company.get("domain", "")
    tagline = company.get("tagline", "")
    if domain and domain.lower() not in sl:
        errors.append(f"Missing wordmark '{domain}'")
    if tagline and tagline.lower() not in sl:
        errors.append(f"Missing tagline '{tagline}'")

    # Forbidden hex colors
    for hex_color in forbidden_colors.get("hex", []):
        if hex_color.lower() in sl:
            errors.append(f"Contains forbidden hex {hex_color}")
    for rgba_prefix in forbidden_colors.get("rgba_prefixes", []):
        if rgba_prefix.lower() in sl:
            errors.append(f"Contains forbidden rgba '{rgba_prefix}...'")

    return len(errors) == 0, errors


def validate_stats_trace(svg: str, source_text: str, source_label: str) -> tuple:
    """Every numeric claim in SVG must appear in source_text (or alt form)."""
    import re
    if not source_text or not source_text.strip():
        return True, [f"WARNING: {source_label} empty, skipping stat-trace"]
    claims = extract_stat_claims_from_svg(svg)
    if not claims:
        return True, []
    src_lower = source_text.lower()
    missing = []
    for c in claims:
        if c.lower() in src_lower:
            continue
        num_match = re.match(r"(\d+(?:\.\d+)?)", c)
        if num_match:
            num = num_match.group(1)
            alts = []
            if c.endswith("%"):
                alts = [f"{num} percent"]
            elif c.lower().endswith("x"):
                alts = [f"{num}x", f"{num} times", f"{num}-fold"]
            elif c.startswith("$"):
                alts = [c.lower(), num]
            if any(a in src_lower for a in alts):
                continue
        missing.append(c)
    if missing:
        return False, [f"SVG stat '{m}' not in {source_label}" for m in missing]
    return True, []


