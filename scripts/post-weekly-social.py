def find_plugin_root() -> Path:
    here = Path(__file__).resolve()
    for ancestor in [here.parent, *here.parents]:
        if (ancestor / ".claude-plugin" / "plugin.json").exists():
            return ancestor
    return here.parent.parent


def load_brand_config(plugin_root: Path, profile: str = None) -> dict:
    """Load brand config. profile lets you use examples/<brand>/config/brand.json."""
    if profile:
        p = plugin_root / "examples" / profile / "config" / "brand.json"
    else:
        p = plugin_root / "config" / "brand.json"
    if not p.exists():
        sys.exit(f"Brand config not found: {p}\nFill from config/brand.template.json first.")
    return json.loads(p.read_text(encoding="utf-8"))


def load_channels_config(plugin_root: Path, profile: str = None) -> dict:
    if profile:
        p = plugin_root / "examples" / profile / "config" / "channels.json"
    else:
        p = plugin_root / "config" / "channels.json"
    if not p.exists():
        sys.exit(f"Channels config not found: {p}\nFill from config/channels.template.json first.")
    return json.loads(p.read_text(encoding="utf-8"))


def read_secret(plugin_root: Path, profile: str, filename: str) -> str:
    """Read gitignored secret file (e.g., .cms-token, .make-webhook-url)."""
    if profile:
        p = plugin_root / "examples" / profile / "config" / filename
    else:
        p = plugin_root / "config" / filename
    if not p.exists():
        sys.exit(f"Secret file missing: {p}")
    return p.read_text(encoding="utf-8").strip()


