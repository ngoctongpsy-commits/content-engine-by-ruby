def render_svg_to_png(svg: str, width: int = 1080) -> bytes:
    """Render SVG to PNG using cairosvg (preferred) or Playwright (fallback)."""
    try:
        import cairosvg
        return cairosvg.svg2png(bytestring=svg.encode("utf-8"), output_width=width)
    except ImportError:
        pass
    # Fallback: Playwright
    try:
        from playwright.sync_api import sync_playwright
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page(viewport={"width": width, "height": width})
            page.set_content(f'<html><body style="margin:0">{svg}</body></html>')
            time.sleep(2.5)
            png = page.screenshot(omit_background=True)
            browser.close()
            return png
    except Exception as e:
        sys.exit(f"SVG render failed: {e}")


def upload_to_cms(channels: dict, plugin_root: Path, profile: str, png_bytes: bytes, filename: str) -> str:
    """Upload PNG to CMS /files endpoint. Returns asset UUID."""
    import requests
    cms = channels["cms"]
    token = read_secret(plugin_root, profile, cms["token_file"])
    base_url = cms["base_url"].rstrip("/")

    if cms["provider"] == "directus":
        files = {
            "file": (filename, png_bytes, "image/png"),
            "title": (None, filename.replace(".png", "").replace("-", " ").title()),
        }
        if cms.get("files_folder_uuid"):
            files["folder"] = (None, cms["files_folder_uuid"])
        r = requests.post(
            f"{base_url}/files",
            headers={"Authorization": f"Bearer {token}"},
            files=files,
            timeout=60,
        )
        if r.status_code in (200, 201):
            return r.json()["data"]["id"]
        sys.exit(f"CMS upload failed: HTTP {r.status_code} {r.text[:300]}")
    else:
        sys.exit(f"CMS provider not supported: {cms['provider']}")


def post_to_webhook(webhook_url: str, payload: dict) -> tuple:
    import requests
    r = requests.post(
        webhook_url,
        headers={"Content-Type": "application/json"},
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        timeout=30,
    )
    return r.status_code, r.text


def verify_make_executions(channels: dict, plugin_root: Path, profile: str, fire_time_utc: datetime, wait_seconds: int = 90) -> dict:
    """Query Make.com API to verify executions succeeded after webhook fire."""
    import requests
    social = channels["social"]
    api_token_file = social.get("make_api_token_file")
    if not api_token_file:
        return {"ok": False, "reason": "make_api_token_file not configured", "skip": True}
    try:
        api_token = read_secret(plugin_root, profile, api_token_file)
    except SystemExit:
        return {"ok": False, "reason": "Make API token file not present", "skip": True}
    scenario_id = social.get("make_scenario_id", "").strip()
    base_url = social.get("make_base_url", "https://eu1.make.com").rstrip("/")
    if not scenario_id or scenario_id.startswith("REPLACE"):
        return {"ok": False, "reason": "make_scenario_id not configured", "skip": True}

    print(f"\nWaiting {wait_seconds}s for Make.com to process webhooks...")
    time.sleep(wait_seconds)

    url = f"{base_url}/api/v2/scenarios/{scenario_id}/logs?limit=10"
    try:
        r = requests.get(url, headers={"Authorization": f"Token {api_token}"}, timeout=30)
        if r.status_code != 200:
            return {"ok": False, "reason": f"Make API HTTP {r.status_code}: {r.text[:200]}", "executions": []}
        all_logs = r.json().get("scenarioLogs", []) or r.json().get("data", [])
        window_start = (fire_time_utc - timedelta(minutes=1)).replace(tzinfo=timezone.utc)
        window_end = (fire_time_utc + timedelta(minutes=5)).replace(tzinfo=timezone.utc)
        recent = []
        for log in all_logs:
            started = log.get("startedAt") or log.get("started_at") or log.get("timestamp")
            if not started:
                continue
            try:
                t = datetime.fromisoformat(started.replace("Z", "+00:00"))
                if window_start <= t <= window_end:
                    recent.append(log)
            except Exception:
                pass
        if not recent:
            return {"ok": False, "reason": "No executions in 5-min window (scenario may be Inactive)"}
        errors = [e for e in recent if str(e.get("status", "")).lower() in ("error", "failed", "3")]
        if errors:
            err = errors[0].get("error") or errors[0].get("message") or "unknown"
            return {"ok": False, "reason": f"{len(errors)}/{len(recent)} executions failed", "details": err}
        return {"ok": True, "reason": f"{len(recent)} executions completed"}
    except Exception as e:
        return {"ok": False, "reason": f"API call failed: {e}"}


def notify_telegram(channels: dict, plugin_root: Path, profile: str, message: str) -> bool:
    """Send Telegram message via bot API. Returns True on success."""
    import urllib.parse, urllib.request
    notif_file = channels.get("notifications", {}).get("telegram", {}).get("config_file")
    if not notif_file:
        return False
    if profile:
        p = plugin_root / "examples" / profile / "config" / notif_file
    else:
        p = plugin_root / "config" / notif_file
    if not p.exists():
        return False
    try:
        cfg = json.loads(p.read_text(encoding="utf-8"))
        bot_token = cfg.get("bot_token", "").strip()
        chat_id = cfg.get("chat_id", "").strip()
        if not bot_token or not chat_id:
            return False
        url = (
            f"https://api.telegram.org/bot{bot_token}/sendMessage"
            f"?chat_id={urllib.parse.quote(str(chat_id))}"
            f"&text={urllib.parse.quote(message)}"
        )
        req = urllib.request.Request(url, headers={"User-Agent": "ContentEngineByRuby"})
        urllib.request.urlopen(req, timeout=15)
        return True
    except Exception as e:
        print(f"  Telegram notify failed: {e}")
        return False


