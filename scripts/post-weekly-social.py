def main():
    ap = argparse.ArgumentParser(description="Fire weekly social packet via Make.com webhook. Config-driven, brand-agnostic.")
    ap.add_argument("--file", help="Specific JSON file. Default: newest in outputs/social/pending/")
    ap.add_argument("--profile", help="Use examples/<profile>/config/ instead of config/. E.g. --profile luna-base")
    ap.add_argument("--dry-run", action="store_true", help="Preview payloads, skip upload + fire")
    ap.add_argument("--no-archive", action="store_true", help="Don't move JSON to processed/ after fire")
    args = ap.parse_args()

    plugin_root = find_plugin_root()
    print(f"Plugin root: {plugin_root}")
    brand = load_brand_config(plugin_root, args.profile)
    channels = load_channels_config(plugin_root, args.profile)
    print(f"Brand: {brand['company']['name']}")

    # Find pending JSON
    if args.file:
        json_path = Path(args.file)
        if not json_path.is_absolute():
            json_path = plugin_root / json_path
    else:
        if args.profile:
            pending_dir = plugin_root / "examples" / args.profile / "outputs" / "social" / "pending"
        else:
            pending_dir = plugin_root / "outputs" / "social" / "pending"
        candidates = sorted(pending_dir.glob("weekly-*.json"), key=lambda p: p.stat().st_mtime, reverse=True)
        if not candidates:
            sys.exit(f"No pending JSON in {pending_dir}")
        json_path = candidates[0]
    print(f"Packet: {json_path}")

    packet = json.loads(json_path.read_text(encoding="utf-8"))
    post_type = packet.get("post_type", "blog_driver")
    print(f"Post type: {post_type}")

    # Validators
    li_ok, li_errs = validate_post_text(packet["linkedin_post"], brand, "LinkedIn")
    fb_ok, fb_errs = validate_post_text(packet["facebook_post"], brand, "Facebook")
    if not (li_ok and fb_ok):
        for e in li_errs + fb_errs:
            print(f"  - {e}")
        sys.exit("Post text validation FAILED. Fix packet and re-run.")

    # Image provider: 'canva' (per-channel PNGs generated by the skill) or 'svg' (legacy render).
    img_provider = packet.get("image_provider") or brand.get("format", {}).get("images", {}).get("provider", "svg")
    canva_mode = img_provider == "canva" and bool(packet.get("image_linkedin_path") or packet.get("image_facebook_path"))

    svg = packet.get("clickbait_svg")
    if not canva_mode:
        # Legacy SVG path: validate the SVG + stat-trace.
        if not svg:
            sys.exit("No clickbait_svg in packet and image provider is not canva.")
        sv_ok, sv_errs = validate_clickbait_svg(svg, brand)
        if not sv_ok:
            for e in sv_errs:
                print(f"  - {e}")
            sys.exit("SVG validation FAILED.")
        if post_type == "blog_driver":
            stat_source = packet.get("blog_html", "")
            stat_label = "blog_html"
        else:
            stats_blob = json.dumps(brand.get("validated_stats", {}).get("entries", []), ensure_ascii=False)
            stat_source = stats_blob
            stat_label = "brand.validated_stats"
        st_ok, st_errs = validate_stats_trace(svg, stat_source, stat_label)
        if not st_ok:
            for e in st_errs:
                print(f"  - {e}")
            sys.exit("Stat-trace FAILED.")

    print(f"All validators PASS. Image provider: {'canva' if canva_mode else 'svg'}")

    if args.dry_run:
        print("\n[DRY RUN] Skipping CMS upload + webhook fire.")
        return

    cms = channels["cms"]
    image_basename = packet.get("blog_slug") or packet.get("feature_specific", "social-card").lower().replace(" ", "-")[:60]

    def channel_image_url(channel_field, cache):
        """Hosted image URL for this channel. Canva: per-channel PNG; SVG: one shared render."""
        if canva_mode:
            rel = packet.get("image_linkedin_path") if "linkedin" in channel_field else packet.get("image_facebook_path")
            rel = rel or packet.get("image_linkedin_path") or packet.get("image_facebook_path")
            png_file = json_path.parent / Path(rel).name
            if not png_file.exists():
                sys.exit(f"Canva image not found: {png_file}")
            key = png_file.name
            if key not in cache:
                data = png_file.read_bytes()
                uuid = upload_to_cms(channels, plugin_root, args.profile, data, key)
                cache[key] = cms["image_url_pattern"].format(base_url=cms["base_url"].rstrip("/"), uuid=uuid)
            return cache[key]
        if "svg_render" not in cache:
            social_size = brand.get("svg_figure", {}).get("social_card_size_px", 1080)
            data = render_svg_to_png(svg, width=social_size)
            uuid = upload_to_cms(channels, plugin_root, args.profile, data, f"{image_basename}-weekly-social.png")
            cache["svg_render"] = cms["image_url_pattern"].format(base_url=cms["base_url"].rstrip("/"), uuid=uuid)
        return cache["svg_render"]

    webhook_url = read_secret(plugin_root, args.profile, channels["social"]["make_webhook_url_file"])
    fire_time_utc = datetime.utcnow()
    all_ok = True
    upload_cache = {}
    for ch_name, ch_cfg in channels["social"]["channels"].items():
        if not ch_cfg.get("enabled"):
            continue
        channel_field = ch_cfg["channel_field_value"]
        image_url = channel_image_url(channel_field, upload_cache)
        payload = {
            "blog_title": packet.get("blog_title") or packet.get("feature_specific", ""),
            "blog_url": packet.get("blog_url") or brand["company"]["url"],
            "post_text": packet["linkedin_post" if "linkedin" in channel_field else "facebook_post"],
            "post_visibility": ch_cfg.get("post_visibility", "PUBLIC"),
            "image_url": image_url,
            "image_title": packet.get("image_title", ""),
            "image_alt": packet.get("image_alt", ""),
            "channel": channel_field,
            "post_type": post_type,
            "schedule_iso": "",
        }
        status, body = post_to_webhook(webhook_url, payload)
        print(f"  {ch_name}: image {image_url} -> HTTP {status}")
        if not (200 <= status < 300):
            all_ok = False

    # Verify Make.com executions
    if all_ok:
        result = verify_make_executions(channels, plugin_root, args.profile, fire_time_utc)
        if result.get("skip"):
            msg = (
                f"Social posts fired (verification skipped)\n"
                f"Brand: {brand['company']['name']}\n"
                f"Time: {fire_time_utc.strftime('%Y-%m-%d %H:%M UTC')}\n"
                f"Check feeds in 5 min."
            )
        elif result["ok"]:
            print(f"\nVerification PASS: {result['reason']}")
            feed_links = [c.get("feed_url", "") for c in channels["social"]["channels"].values() if c.get("enabled") and c.get("feed_url")]
            msg = (
                f"Social posts: POSTED\n"
                f"Brand: {brand['company']['name']}\n"
                f"Time: {fire_time_utc.strftime('%Y-%m-%d %H:%M UTC')}\n"
                f"Verified: {result['reason']}\n"
                + "\n".join(feed_links)
            )
        else:
            print(f"\nVerification FAIL: {result['reason']}")
            msg = (
                f"SOCIAL POSTS FAILED\n"
                f"Brand: {brand['company']['name']}\n"
                f"Time: {fire_time_utc.strftime('%Y-%m-%d %H:%M UTC')}\n"
                f"Reason: {result['reason']}\n"
                f"Details: {str(result.get('details',''))[:200]}\n"
                f"Action: check Make.com History, fix, re-fire."
            )
        notify_telegram(channels, plugin_root, args.profile, msg)

    if all_ok and not args.no_archive:
        processed_dir = json_path.parent.parent / "processed"
        processed_dir.mkdir(parents=True, exist_ok=True)
        target = processed_dir / json_path.name
        json_path.rename(target)
        print(f"Archived: {target.name}")

    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
