"""
publish-blog.py - config-driven blog HTML publisher (generic, brand-agnostic)

Reads:
  - config/brand.json - palette, typography, voice rules, validated stats
  - config/channels.json - CMS provider, base_url, token_file, fields mapping
  - outputs/blogs/draft-YYYY-MM-DD-slot-X-*.html - draft generated by blog skill

Output:
  - Render best figure (highest visual richness score) as PNG thumbnail
  - Validate HTML body against brand rules (forbidden chars, palette, voice)
  - Inline CSS to be CMS-safe
  - POST thumbnail to CMS /files
  - POST blog body to CMS /items/<collection> with field mapping from channels.json
  - Telegram alert success or failure
  - Move draft to outputs/blogs/published-YYYYMMDD-<slug>.html

Generic - no hardcoded brand. Forks for other brands just edit config/.
Built by Ruby for the Content Engine plugin.

Usage:
  python scripts/publish-blog.py --slot A
  python scripts/publish-blog.py --slot B --profile luna-base
  python scripts/publish-blog.py --draft outputs/blogs/draft-2026-06-01-slot-A-foo.html
"""
