# Main
# ============================================================

def main():
    parser = argparse.ArgumentParser(description="Publish blog draft to CMS (generic, config-driven)")
    parser.add_argument("--slot", choices=["A", "B", "C"], help="Slot label - finds today's draft for this slot")
    parser.add_argument("--draft", help="Explicit draft path (overrides --slot)")
    parser.add_argument("--profile", help="Use examples/<profile>/config/ instead of config/")
    parser.add_argument("--date", help="Target date YYYY-MM-DD (default today, only with --slot)")
    parser.add_argument("--dry-run", action="store_true", help="Validate + render but do not POST to CMS")
    args = parser.parse_args()

    if not args.slot and not args.draft:
        parser.error("--slot or --draft required")

    plugin_root = find_plugin_root()
    brand = load_brand_config(plugin_root, args.profile)
    channels = load_channels_config(plugin_root, args.profile)

    # Resolve draft
    if args.draft:
        draft_path = Path(args.draft)
        if not draft_path.is_absolute():
            draft_path = plugin_root / args.draft
    else:
        draft_path = find_draft_for_slot(drafts_dir(plugin_root, args.profile), args.slot, args.date)

    if not draft_path.exists():
        sys.exit(f"Draft not found: {draft_path}")

    print(f"[publish] draft: {draft_path.name}", flush=True)
    html = draft_path.read_text(encoding="utf-8")
    slug = extract_slug_from_draft(draft_path)

    # Validate HTML
    ok, errors = validate_body_html(html, brand)
    if not ok:
        msg = f"[publish] VALIDATION FAILED for {draft_path.name}:\n  - " + "\n  - ".join(errors)
        print(msg, flush=True)
        notify_telegram(channels, plugin_root, args.profile,
                        f"*Blog publish failed* (validation)\n`{draft_path.name}`\n\n" + "\n".join(f"- {e}" for e in errors))
        sys.exit(1)
    print(f"[publish] validation: ok", flush=True)

    # Pick best figure + render thumbnail
    figures = extract_figures(html)
    idx, best_svg, best_score = pick_best_figure(figures)
    thumbnail_id = None
    if best_svg:
        print(f"[publish] picked figure {idx+1}/{len(figures)} (score={best_score:.1f}) for thumbnail", flush=True)
        png = render_svg_to_png(best_svg, width=1200)
        if args.dry_run:
            preview = drafts_dir(plugin_root, args.profile) / f"_preview-{slug}.png"
            preview.write_bytes(png)
            print(f"[publish] dry-run: wrote preview to {preview}", flush=True)
        elif channels.get("cms", {}).get("provider") == "none":
            # No CMS: stash the thumbnail next to the local HTML output.
            ready = outputs_root(plugin_root, args.profile) / "blogs" / "ready"
            ready.mkdir(parents=True, exist_ok=True)
            (ready / f"{slug}.png").write_bytes(png)
            print(f"[publish] no-CMS: thumbnail saved to {ready / (slug + '.png')}", flush=True)
        else:
            thumbnail_id = upload_thumbnail(channels, plugin_root, args.profile, png, f"{slug}.png")
            print(f"[publish] thumbnail uploaded: {thumbnail_id}", flush=True)
    else:
        print("[publish] no SVG figures found - publishing without thumbnail", flush=True)

    # Build + POST payload
    payload = build_post_payload(channels, brand, html, slug, thumbnail_id)

    if args.dry_run:
        print(f"[publish] dry-run: payload fields = {list(payload.keys())}", flush=True)
        return

    provider = channels.get("cms", {}).get("provider")
    if provider == "none":
        # No CMS: write the final inlined HTML for manual / GitHub publishing. Nothing is posted.
        ready = outputs_root(plugin_root, args.profile) / "blogs" / "ready"
        ready.mkdir(parents=True, exist_ok=True)
        body_html = inline_css_into_body(html)
        out_file = ready / f"{slug}.html"
        out_file.write_text(body_html, encoding="utf-8")
        print(f"[publish] no-CMS: wrote {out_file} (commit to GitHub or upload manually)", flush=True)
        post_id = slug
        posted = {"id": slug, "_local_path": str(out_file)}
    else:
        posted = post_blog(channels, plugin_root, args.profile, payload)
        post_id = posted.get("id") or posted.get(channels.get("cms", {}).get("fields", {}).get("slug", "slug"))
        print(f"[publish] posted: id={post_id}", flush=True)

    # Move draft to published archive
    archive = drafts_dir(plugin_root, args.profile) / f"published-{datetime.now().strftime('%Y%m%d')}-{slug}.html"
    draft_path.rename(archive)
    print(f"[publish] archived to {archive.name}", flush=True)

    # Public URL pattern from channels.json
    cms = channels.get("cms", {})
    public_url = cms.get("public_url_pattern", "").replace("{slug}", slug)

    notify_telegram(channels, plugin_root, args.profile,
                    f"*Blog published*\n`{slug}`\n{public_url}\n\nFigure {idx+1}/{len(figures)} as thumbnail.")


if __name__ == "__main__":
    main()
