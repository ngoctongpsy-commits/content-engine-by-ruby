def outputs_root(plugin_root: Path, profile: str = None) -> Path:
    """Where drafts live. Default plugin_root/outputs/, profile overrides to examples/<profile>/outputs/."""
    if profile:
        return plugin_root / "examples" / profile / "outputs"
    return plugin_root / "outputs"


def drafts_dir(plugin_root: Path, profile: str = None) -> Path:
    d = outputs_root(plugin_root, profile) / "blogs"
    d.mkdir(parents=True, exist_ok=True)
    return d


# ============================================================
# Network + DNS preflight (lessons from May 2 incident)
# ============================================================

def dns_preflight(host: str, retries: int = 3, wait_seconds: int = 30) -> bool:
    """Resolve host with retries. Returns True if resolves, False if all retries fail."""
    last_err = None
    for attempt in range(retries + 1):
        try:
            socket.gethostbyname(host)
            return True
        except socket.gaierror as e:
            last_err = e
            if attempt < retries:
                sleep_for = wait_seconds * (2 ** attempt) if attempt > 0 else wait_seconds
                print(f"[dns] resolve {host} failed (attempt {attempt+1}): {e}. sleeping {sleep_for}s", flush=True)
                time.sleep(sleep_for)
    print(f"[dns] ABORT - {host} unreachable after {retries+1} attempts. Last error: {last_err}", flush=True)
    return False


def requests_with_retry(method: str, url: str, retries: int = 2, **kwargs):
    """Wrap requests with ConnectionError/Timeout retry."""
    import requests
    last_err = None
    for attempt in range(retries + 1):
        try:
            return requests.request(method, url, **kwargs)
        except (requests.ConnectionError, requests.Timeout) as e:
            last_err = e
            if attempt < retries:
                sleep_for = 30 * (2 ** attempt)
                print(f"[net] {method} {url} failed (attempt {attempt+1}): {e}. sleeping {sleep_for}s", flush=True)
                time.sleep(sleep_for)
    raise last_err


